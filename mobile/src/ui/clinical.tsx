export const SIMULATION_FOOTNOTE =
  'Synthetic phantom generated by code. Spectral views computed from a simulated optical module. ' +
  'Processing runs on the server in this prototype; the target architecture moves it on-device. ' +
  'No diagnosis, cancer probability or risk score. AI suggestions are research-mode outputs of small models trained on simulated data only.';

const VIEW_OPTIONS = [
  { value: 'standard', label: 'Standard' },
  { value: 'pigment', label: 'Pigment' },
  { value: 'vascular', label: 'Vascular' },
  { value: 'evidence', label: 'AI evidence' },
] as const;
export type ViewName = (typeof VIEW_OPTIONS)[number]['value'];

const VIEW_HELP: Record<ViewName, string> = {
  standard: 'Pseudo-colour image from the blue, green and red bands.',
  pigment: 'Estimated melanin map (darker = more pigment).',
  vascular: 'Estimated hemoglobin map (darker red = more blood).',
  evidence:
    'Where the pattern evidence sits: amber = extra pigment, red = extra blood, pink = brightest blood spots, compared with the surrounding skin. These are the maps the triage model reads.',
};

export function SpectralViews({
  capture,
  caption,
  view: controlledView,
  onViewChange,
  allowAll = false,
}: {
  capture: Capture;
  /** Offer an "All" tab that shows the three views side by side (wide screens). */
  allowAll?: boolean;
  /** Shown above the image and in the full-screen viewer, e.g. "Day 30 · 28.7 mm²". */
  caption?: string;
  view?: ViewName;
  onViewChange?: (view: ViewName) => void;
}) {
  const [ownView, setOwnView] = useState<ViewName>('standard');
  const [all, setAll] = useState(false);
  const [zoomed, setZoomed] = useState(false);
  const [zoomAll, setZoomAll] = useState<{ uri: string; title: string } | null>(null);
  const view = controlledView ?? ownView;
  const setView = onViewChange ?? setOwnView;
  const available = VIEW_OPTIONS.filter((o) => capture.views[o.value]);
  const current = capture.views[view] ? view : 'standard';
  const uri = absoluteUrl(capture.views[current]);
  const label = `${VIEW_OPTIONS.find((o) => o.value === current)?.label} view${caption ? ` · ${caption}` : ''}`;
  return (
    <View style={{ gap: spacing.md }} testID="spectral-views">
      <Chips
        options={allowAll ? [...available, { value: 'all' as const, label: 'All side by side' }] : available}
        value={all ? 'all' : current}
        onChange={(v) => {
          if (v === 'all') {
            setAll(true);
          } else {
            setAll(false);
            setView(v);
          }
        }}
        testIDPrefix="view"
      />
      {caption ? <Text style={styles.caption}>{caption}</Text> : null}
      {all ? (
        <View style={styles.compareRow} testID="views-all">
          {available.map((o) => {
            const viewUri = absoluteUrl(capture.views[o.value]);
            return (
              <Pressable
                key={o.value}
                style={styles.compareCell}
                onPress={() => setZoomAll({ uri: viewUri, title: `${o.label} view${caption ? ` · ${caption}` : ''}` })}
              >
                <Image source={{ uri: viewUri }} style={styles.compareImage} />
                <Text style={styles.visitDay}>{o.label}</Text>
              </Pressable>
            );
          })}
          <ImageViewer uri={zoomAll?.uri ?? null} title={zoomAll?.title ?? ''} onClose={() => setZoomAll(null)} />
        </View>
      ) : (
      <Pressable
        style={styles.imageFrame}
        onPress={() => setZoomed(true)}
        accessibilityRole="imagebutton"
        accessibilityLabel={`${current} view (simulated), tap to enlarge`}
      >
        <Image source={{ uri }} style={styles.image} resizeMode="contain" testID={`view-image-${current}`} />
        <View style={styles.badgeOverlay}>
          <SimulatedBadge />
        </View>
        <View style={styles.zoomHint}>
          <Text style={styles.zoomHintText}>Tap to enlarge</Text>
        </View>
      </Pressable>
      )}
      <Muted>{all ? 'All views of the same capture.' : VIEW_HELP[current]}</Muted>
      <ImageViewer uri={zoomed ? uri : null} title={label} onClose={() => setZoomed(false)} />
    </View>
  );
}

/** First visit next to the selected (default: latest) visit, same view, with the area change. */
export function VisitCompare({ captures, selectedId }: { captures: Capture[]; selectedId?: string }) {
  const [view, setView] = useState<ViewName>('standard');
  const [zoom, setZoom] = useState<{ uri: string; title: string } | null>(null);
  const visits = captures.filter((c) => c.status === 'processed');
  if (visits.length < 2) return null;
  const first = visits[0];
  const second = visits.find((c) => c.id === selectedId && c.id !== first.id) ?? visits[visits.length - 1];
  const change =
    first.area_mm2 && second.area_mm2 ? ((second.area_mm2 - first.area_mm2) / first.area_mm2) * 100 : null;
  const dayLabel = (c: Capture) => `Day ${String(visitDay(c.captured_at, first.captured_at)).padStart(2, '0')}`;
  const viewLabel = VIEW_OPTIONS.find((o) => o.value === view)?.label;
  return (
    <Card testID="visit-compare">
      <Row style={{ justifyContent: 'space-between' }}>
        <Heading>
          Compare {dayLabel(first)} → {dayLabel(second)}
        </Heading>
        <SimulatedBadge />
      </Row>
      <Chips options={VIEW_OPTIONS} value={view} onChange={setView} testIDPrefix="compare-view" />
      <View style={styles.compareRow}>
        {[first, second].map((c) => {
          const uri = absoluteUrl(c.views[view] ?? c.views.standard);
          const title = `${viewLabel} · ${dayLabel(c)} · ${formatArea(c.area_mm2)}`;
          return (
            <Pressable key={c.id} style={styles.compareCell} onPress={() => setZoom({ uri, title })}>
              <Image source={{ uri }} style={styles.compareImage} />
              <Text style={styles.visitDay}>{dayLabel(c)}</Text>
              <Text style={styles.visitArea}>{formatArea(c.area_mm2)}</Text>
              <Muted>{formatDate(c.captured_at)}</Muted>
            </Pressable>
          );
        })}
      </View>
      {change !== null ? (
        <View style={[styles.changePill, change > 0 ? styles.changeUp : styles.changeFlat]}>
          <Text style={styles.changeText} testID="compare-change">
            Area {change >= 0 ? '+' : ''}
            {change.toFixed(0)}% ({formatArea(first.area_mm2)} → {formatArea(second.area_mm2)})
          </Text>
        </View>
      ) : null}
      <Muted>Same view, same scale. Area from automated segmentation of simulated images.</Muted>
      <ImageViewer uri={zoom?.uri ?? null} title={zoom?.title ?? ''} onClose={() => setZoom(null)} />
    </Card>
  );
}

export function QCCard({ capture, onRetake }: { capture: Capture; onRetake?: () => void }) {
  const qc = capture.qc;
  return (
    <Card
      style={{ borderColor: qc.passed ? colors.success : colors.danger }}
      testID={qc.passed ? 'qc-passed' : 'qc-failed'}
    >
      <Row>
        <Pill label={qc.passed ? 'Quality check passed' : 'Retake needed'} tone={qc.passed ? 'success' : 'danger'} />
        <Muted>Automated image quality check (not a diagnosis)</Muted>
      </Row>
      {qc.guidance.map((g) => (
        <Text key={g} style={styles.guidance}>
          {g}
        </Text>
      ))}
      {capture.quality_model ? (
        <Muted testID="qc-second-opinion">
          Second opinion, learned model (advisory):{' '}
          {qualityStep(capture.quality_model, qc.passed).result}
        </Muted>
      ) : null}
      {!qc.passed && onRetake ? (
        <Pressable onPress={onRetake} accessibilityRole="button" style={styles.retake} testID="retake">
          <Text style={styles.retakeText}>Retake</Text>
        </Pressable>
      ) : null}
    </Card>
  );
}

/** Day 01 / 14 / 30 strip with area change against the first visit. */
export function HistoryStrip({
  captures,
  currentId,
  onSelect,
}: {
  captures: Capture[];
  currentId?: string;
  onSelect?: (capture: Capture) => void;
}) {
  const visits = captures.filter((c) => c.status === 'processed');
  if (visits.length === 0) return null;
  const first = visits[0];
  const last = visits[visits.length - 1];
  const change =
    first.area_mm2 && last.area_mm2 && visits.length > 1
      ? ((last.area_mm2 - first.area_mm2) / first.area_mm2) * 100
      : null;
  return (
    <Card testID="history-strip">
      <Row style={{ justifyContent: 'space-between' }}>
        <Heading>Lesion history</Heading>
        <SimulatedBadge />
      </Row>
      <View style={styles.strip}>
        {visits.map((c) => {
          const day = visitDay(c.captured_at, first.captured_at);
          const selected = c.id === currentId;
          return (
            <Pressable
              key={c.id}
              onPress={onSelect ? () => onSelect(c) : undefined}
              disabled={!onSelect}
              style={[styles.visit, selected && styles.visitSelected]}
              testID={`visit-day-${day}`}
            >
              <Image source={{ uri: absoluteUrl(c.views.standard) }} style={styles.thumb} />
              <Text style={styles.visitDay}>Day {String(day).padStart(2, '0')}</Text>
              <Text style={styles.visitArea}>{formatArea(c.area_mm2)}</Text>
              <Muted>{formatDate(c.captured_at)}</Muted>
            </Pressable>
          );
        })}
      </View>
      {change !== null ? (
        <Text style={styles.change} testID="area-change">
          Area {change >= 0 ? '+' : ''}
          {change.toFixed(0)}% since Day 01 ({formatArea(first.area_mm2)} → {formatArea(last.area_mm2)})
        </Text>
      ) : (
        <Muted>Capture again at follow-up to track change.</Muted>
      )}
      <Muted>Area from automated segmentation of simulated images; measurement, not diagnosis.</Muted>
    </Card>
  );
}

