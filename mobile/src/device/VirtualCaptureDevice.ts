import type { ImageSourcePropType } from 'react-native';

import { api, ApiError } from '@/api/client';
import { absoluteUrl } from '@/api/config';

import {
  type CaptureDevice,
  type CaptureProgress,
  type DeviceStatus,
  FRAME_NAMES,
  type FrameName,
  type FramePart,
  type FrameSet,
} from './CaptureDevice';
import { loadFrame, loadRemoteFrame } from './frameSource';
import { PHANTOMS } from './phantoms.generated';
import { uuidv4 } from './uuid';

export const DEFAULT_PHANTOM = 'acral_dark_d30';
/** A fresh capture from the server-side simulator, consistent with the lesion's earlier ones. */
export const AUTO = 'auto';
// Paces the band cycle so the clinician sees each LED fire, then its frame (about 2.8 s in total).
const FIRE_MS = 300;
const SHOW_MS = 250;

const STATUS: DeviceStatus = {
  connected: true,
  deviceId: 'virtual-001',
  label: 'Virtual module',
  simulated: true,
};

type Source = {
  phantomId: string;
  frame: (name: FrameName) => Promise<FramePart>;
  preview: (name: FrameName) => ImageSourcePropType;
};

/**
 * Simulated module. AUTO asks the server simulator for a new frame set of this lesion (new noise
 * and hand motion each time, same lesion identity); offline, or with a phantom picked in the
 * developer options, it reads the bundled frame sets (generated by backend/simulator).
 */
export class VirtualCaptureDevice implements CaptureDevice {
  private phantomId = AUTO;
  private lesionId: string | null = null;

  /** Simulator only: which lesion the spacer is on, so captures stay consistent per lesion. */
  aimAt(lesionId: string) {
    this.lesionId = lesionId;
  }

  async connect(): Promise<DeviceStatus> {
    return STATUS;
  }

  status(): DeviceStatus {
    return STATUS;
  }

  /** Dev-only: choose which phantom the next capture returns. */
  selectPhantom(id: string) {
    if (id !== AUTO && !PHANTOMS.some((p) => p.id === id)) throw new Error(`Unknown phantom ${id}`);
    this.phantomId = id;
  }

  selectedPhantom(): string {
    return this.phantomId;
  }

  private bundled(id: string): Source {
    const phantom = PHANTOMS.find((p) => p.id === id);
    if (!phantom) throw new Error(`Unknown phantom ${id}`);
    return {
      phantomId: phantom.id,
      frame: (name) => loadFrame(phantom.frames[name], name),
      preview: (name) => phantom.previews[name],
    };
  }

  private async source(): Promise<Source> {
    if (this.phantomId !== AUTO || !this.lesionId) {
      return this.bundled(this.phantomId === AUTO ? DEFAULT_PHANTOM : this.phantomId);
    }
    try {
      const sim = await api.simulateCapture({ lesion_id: this.lesionId });
      return {
        phantomId: sim.phantom_id,
        frame: (name) => loadRemoteFrame(absoluteUrl(sim.frames[name]), name),
        preview: (name) => ({ uri: absoluteUrl(sim.previews[name]) }),
      };
    } catch (e) {
      // Offline: the module still works on the bundled frame sets; the upload queue takes over.
      if (e instanceof ApiError && e.status === 0) return this.bundled(DEFAULT_PHANTOM);
      throw e;
    }
  }

  async capture(onProgress?: (progress: CaptureProgress) => void): Promise<FrameSet> {
    const source = await this.source();
    const frames = {} as Record<FrameName, FramePart>;
    for (const [index, name] of FRAME_NAMES.entries()) {
      const total = FRAME_NAMES.length;
      onProgress?.({ step: name, index, total, state: 'firing' });
      const [frame] = await Promise.all([
        source.frame(name),
        new Promise((resolve) => setTimeout(resolve, FIRE_MS)),
      ]);
      frames[name] = frame;
      onProgress?.({ step: name, index, total, state: 'captured', preview: source.preview(name) });
      await new Promise((resolve) => setTimeout(resolve, SHOW_MS));
    }
    return {
      id: uuidv4(),
      capturedAt: new Date().toISOString(),
      deviceId: STATUS.deviceId,
      phantomId: source.phantomId,
      frames,
    };
  }
}

export const captureDevice = new VirtualCaptureDevice();
