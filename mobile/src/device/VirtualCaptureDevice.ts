import {
  type CaptureDevice,
  type CaptureProgress,
  type DeviceStatus,
  FRAME_NAMES,
  type FrameName,
  type FramePart,
  type FrameSet,
} from './CaptureDevice';
import { loadFrame } from './frameSource';
import { PHANTOMS } from './phantoms.generated';
import { uuidv4 } from './uuid';

export const DEFAULT_PHANTOM = 'acral_dark_d30';
// Paces the band cycle so the clinician sees each LED fire, then its frame (about 2.8 s in total).
const FIRE_MS = 300;
const SHOW_MS = 250;

const STATUS: DeviceStatus = {
  connected: true,
  deviceId: 'virtual-001',
  label: 'Virtual module',
  simulated: true,
};

/** Reads bundled synthetic phantom frame sets (generated by backend/simulator). */
export class VirtualCaptureDevice implements CaptureDevice {
  private phantomId = DEFAULT_PHANTOM;

  async connect(): Promise<DeviceStatus> {
    return STATUS;
  }

  status(): DeviceStatus {
    return STATUS;
  }

  /** Dev-only: choose which phantom the next capture returns. */
  selectPhantom(id: string) {
    if (!PHANTOMS.some((p) => p.id === id)) throw new Error(`Unknown phantom ${id}`);
    this.phantomId = id;
  }

  selectedPhantom(): string {
    return this.phantomId;
  }

  async capture(onProgress?: (progress: CaptureProgress) => void): Promise<FrameSet> {
    const phantom = PHANTOMS.find((p) => p.id === this.phantomId);
    if (!phantom) throw new Error(`Unknown phantom ${this.phantomId}`);
    const frames = {} as Record<FrameName, FramePart>;
    for (const [index, name] of FRAME_NAMES.entries()) {
      const total = FRAME_NAMES.length;
      onProgress?.({ step: name, index, total, state: 'firing' });
      const [frame] = await Promise.all([
        loadFrame(phantom.frames[name], name),
        new Promise((resolve) => setTimeout(resolve, FIRE_MS)),
      ]);
      frames[name] = frame;
      onProgress?.({ step: name, index, total, state: 'captured', preview: phantom.previews[name] });
      await new Promise((resolve) => setTimeout(resolve, SHOW_MS));
    }
    return {
      id: uuidv4(),
      capturedAt: new Date().toISOString(),
      deviceId: STATUS.deviceId,
      phantomId: phantom.id,
      frames,
    };
  }
}

export const captureDevice = new VirtualCaptureDevice();
