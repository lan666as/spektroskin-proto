"""Synthetic skin phantoms with known melanin and hemoglobin maps.

Every phantom is generated by code from a fixed seed. No real or public images are used.
"""

import zlib
from dataclasses import dataclass

import numpy as np
from scipy import ndimage

from app.processing.optics import FRAME_SIZE, MM_PER_PX

# Illustrative background melanin per tone; ordered, not fitted to measured skin.
TONE_MELANIN = {"light": 0.5, "medium": 1.0, "dark": 1.7}
TONE_FITZPATRICK = {"light": "III", "medium": "IV", "dark": "V"}
BACKGROUND_HB = 0.15


@dataclass(frozen=True)
class PhantomSpec:
    id: str
    lesion: str  # pigmented | vascular | mixed
    tone: str  # light | medium | dark
    acral: bool = False
    area_mm2: float = 24.0
    variant: str | None = None  # blur | glare
    shape_seed: str | None = None  # phantoms sharing a shape (growth series)
    description: str = ""

    @property
    def fitzpatrick(self) -> str:
        return TONE_FITZPATRICK[self.tone]


def catalogue() -> list[PhantomSpec]:
    specs = [
        PhantomSpec(
            f"{lesion}_{tone}",
            lesion,
            tone,
            area_mm2={"pigmented": 24.0, "vascular": 20.0, "mixed": 26.0}[lesion],
            description=f"{lesion.capitalize()} lesion, {tone} skin tone",
        )
        for lesion in ("pigmented", "vascular", "mixed")
        for tone in ("light", "medium", "dark")
    ]
    specs += [
        PhantomSpec(
            "pigmented_dark_blur",
            "pigmented",
            "dark",
            area_mm2=24.0,
            variant="blur",
            shape_seed="pigmented_dark",
            description="Bad capture: motion/focus blur",
        ),
        PhantomSpec(
            "pigmented_dark_glare",
            "pigmented",
            "dark",
            area_mm2=24.0,
            variant="glare",
            shape_seed="pigmented_dark",
            description="Bad capture: specular glare from an air gap",
        ),
    ]
    specs += [
        PhantomSpec(
            f"acral_dark_d{day:02d}",
            "pigmented",
            "dark",
            acral=True,
            area_mm2=area,
            shape_seed="acral_dark",
            description=f"Acral (sole) pigmented lesion, dark skin tone, visit day {day}",
        )
        for day, area in ((1, 18.0), (14, 22.0), (30, 28.0))
    ]
    return specs


def spec_by_id(phantom_id: str) -> PhantomSpec:
    for spec in catalogue():
        if spec.id == phantom_id:
            return spec
    raise KeyError(phantom_id)


def seed_for(name: str) -> int:
    return zlib.crc32(name.encode())


@dataclass(frozen=True)
class GroundTruth:
    melanin: np.ndarray
    hemoglobin: np.ndarray
    shading: np.ndarray  # band-independent geometric shading (skin lines, ridges)
    mask: np.ndarray
    area_mm2: float


def _smooth_noise(rng: np.random.Generator, sigma: float, size: int = FRAME_SIZE) -> np.ndarray:
    n = ndimage.gaussian_filter(rng.standard_normal((size, size)), sigma)
    return n / (n.std() + 1e-12)


def _lesion_shape(rng: np.random.Generator, area_px: float, size: int = FRAME_SIZE) -> np.ndarray:
    """Soft lesion profile in [0, 1] with an irregular, lobulated border of the given area."""
    yy, xx = np.mgrid[0:size, 0:size].astype(float)
    cy, cx = size / 2 + rng.uniform(-6, 6), size / 2 + rng.uniform(-6, 6)
    theta = np.arctan2(yy - cy, xx - cx)
    dist = np.hypot(yy - cy, xx - cx)
    wobble = np.ones_like(theta)
    for k in range(2, 12):
        amp = rng.uniform(0.3, 1.0) * 0.12 / k**0.8
        wobble += amp * np.cos(k * theta + rng.uniform(0, 2 * np.pi))
    wobble += 0.04 * _smooth_noise(rng, 6, size)
    r0 = np.sqrt(area_px / np.pi)
    for _ in range(4):  # rescale so the hard mask hits the target area
        hard = dist < r0 * wobble
        r0 *= np.sqrt(area_px / max(hard.sum(), 1))
    edge = 1.8
    return 1.0 / (1.0 + np.exp((dist - r0 * wobble) / edge))


def _skin_lines(rng: np.random.Generator, acral: bool, size: int = FRAME_SIZE) -> np.ndarray:
    """Band-independent shading: furrows on general skin, dermatoglyphic ridges on acral skin."""
    yy, xx = np.mgrid[0:size, 0:size].astype(float)
    if acral:
        angle = rng.uniform(0, np.pi)
        u = xx * np.cos(angle) + yy * np.sin(angle)
        warp = 6 * _smooth_noise(rng, 30, size)
        ridges = np.cos(2 * np.pi * (u + warp) / 12.0)  # ~0.5 mm ridge period
        return 1.0 - 0.05 * (ridges + 1) / 2
    shade = np.ones((size, size))
    for _ in range(2):
        angle = rng.uniform(0, np.pi)
        u = xx * np.cos(angle) + yy * np.sin(angle)
        warp = 8 * _smooth_noise(rng, 40, size)
        lines = np.abs(np.sin(np.pi * (u + warp) / rng.uniform(28, 40)))
        shade -= 0.06 * np.exp(-((lines / 0.08) ** 2))
    return shade


def _reticular_network(rng: np.random.Generator, size: int = FRAME_SIZE) -> np.ndarray:
    """Mesh-like modulation in [0, 1] from band-pass noise."""
    band = _smooth_noise(rng, 2.0, size) - 0.6 * _smooth_noise(rng, 4.0, size)
    return np.clip(0.5 + 0.35 * np.tanh(np.abs(band) * 1.5) - 0.2, 0, 1)


def _vessels(rng: np.random.Generator, region: np.ndarray, size: int = FRAME_SIZE) -> np.ndarray:
    """Dotted and short linear vessels inside the lesion region, values in [0, 1]."""
    canvas = np.zeros((size, size))
    ys, xs = np.nonzero(region > 0.5)
    if len(ys) == 0:
        return canvas
    for i in rng.choice(len(ys), size=min(60, len(ys)), replace=False):
        canvas[ys[i], xs[i]] = 1.0
    for _ in range(8):
        i = rng.integers(len(ys))
        y, x = float(ys[i]), float(xs[i])
        heading = rng.uniform(0, 2 * np.pi)
        for _ in range(40):
            heading += rng.normal(0, 0.25)
            y, x = y + np.sin(heading), x + np.cos(heading)
            if 0 <= int(y) < size and 0 <= int(x) < size:
                canvas[int(y), int(x)] = 1.0
    out = ndimage.gaussian_filter(canvas, 1.2)
    return out / (out.max() + 1e-12)


def ground_truth(spec: PhantomSpec) -> GroundTruth:
    shape_rng = np.random.default_rng(seed_for(spec.shape_seed or spec.id))
    tex_rng = np.random.default_rng(seed_for((spec.shape_seed or spec.id) + ":texture"))

    area_px = spec.area_mm2 / (MM_PER_PX**2)
    profile = _lesion_shape(shape_rng, area_px)
    shading = _skin_lines(tex_rng, spec.acral)

    melanin = TONE_MELANIN[spec.tone] * (1 + 0.04 * _smooth_noise(tex_rng, 3))
    melanin = melanin * (1 + 0.03 * _smooth_noise(tex_rng, 25))
    hemoglobin = BACKGROUND_HB * (1 + 0.15 * _smooth_noise(tex_rng, 6))

    if spec.lesion in ("pigmented", "mixed"):
        density = 0.8 + 0.2 * _smooth_noise(tex_rng, 12)
        network = _reticular_network(tex_rng)
        amplitude = 1.6 if spec.lesion == "pigmented" else 1.0
        core = ndimage.gaussian_filter(profile, 12) ** 1.5  # darker centre, lighter rim
        modulation = np.clip(density, 0.5, 1.3) * (0.55 + 0.7 * network) * (0.7 + 0.5 * core)
        lesion_mel = amplitude * profile * modulation
        if spec.acral:
            ridge_phase = (1.0 - shading) / 0.05  # 0 on ridges' crests, 1 in furrows
            lesion_mel *= 0.8 + 0.3 * ridge_phase
        melanin = melanin + lesion_mel
        hemoglobin = hemoglobin + 0.08 * profile
    if spec.lesion in ("vascular", "mixed"):
        vessels = _vessels(tex_rng, profile)
        amplitude = 0.7 if spec.lesion == "vascular" else 0.5
        hemoglobin = hemoglobin + amplitude * profile + 0.8 * vessels * profile

    mask = profile > 0.5
    return GroundTruth(
        melanin=melanin.astype(np.float32),
        hemoglobin=hemoglobin.astype(np.float32),
        shading=shading.astype(np.float32),
        mask=mask,
        area_mm2=float(mask.sum() * MM_PER_PX**2),
    )
