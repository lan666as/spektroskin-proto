"""Generate phantom frame sets, ground truth and the virtual device profile.

    uv run python -m simulator.generate [--mobile ../mobile]

Writes simulator/out/{phantoms,ground_truth,device_profile}. With --mobile, also copies the frame
sets (never ground truth) into the app bundle and writes the TypeScript asset index.
"""

import argparse
import io
import json
import shutil
from pathlib import Path

import numpy as np
from PIL import Image

from app.processing.frameio import decode_png16, encode_png16
from app.processing.optics import BANDS
from simulator.device import capture, factory_profile
from simulator.phantoms import catalogue, ground_truth

OUT = Path(__file__).resolve().parent / "out"


def write_frame_set(directory: Path, frames: dict[str, np.ndarray], dark: np.ndarray, meta: dict):
    directory.mkdir(parents=True, exist_ok=True)
    for band, frame in frames.items():
        (directory / f"{band}.png").write_bytes(encode_png16(frame))
    (directory / "dark.png").write_bytes(encode_png16(dark))
    (directory / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")


def generate(out: Path = OUT) -> list[dict]:
    profile = factory_profile()
    write_frame_set(
        out / "device_profile",
        profile.flat,
        profile.flat_dark,
        {"device_id": profile.device_id, "kind": "factory flat-field", "simulated": True},
    )
    index = []
    (out / "ground_truth").mkdir(parents=True, exist_ok=True)
    for spec in catalogue():
        gt = ground_truth(spec)
        frame_set = capture(spec, gt)
        target = out / "phantoms" / spec.id
        write_frame_set(target, frame_set.frames, frame_set.dark, frame_set.meta)
        np.savez_compressed(
            out / "ground_truth" / f"{spec.id}.npz",
            melanin=gt.melanin,
            hemoglobin=gt.hemoglobin,
            mask=gt.mask,
            area_mm2=gt.area_mm2,
        )
        index.append({**frame_set.meta, "true_area_mm2": round(gt.area_mm2, 2)})
    (out / "index.json").write_text(json.dumps(index, indent=2) + "\n")
    return index


# Display colour per LED in the capture animation (NIR is invisible, so shown as deep magenta).
PREVIEW_RGB = {
    "blue": (59, 130, 246),
    "green": (34, 197, 94),
    "red": (239, 68, 68),
    "nir": (190, 24, 93),
    "dark": (148, 163, 184),
}
PREVIEW_SIZE = 128
DARK_DISPLAY_FULL_SCALE = 8000.0


def preview_png(name: str, raw: np.ndarray, dark: np.ndarray) -> bytes:
    """Small colourised 8-bit preview of one raw frame for the capture animation."""
    raw, dark = raw.astype(np.float64), dark.astype(np.float64)
    if name == "dark":
        level = np.clip(raw / DARK_DISPLAY_FULL_SCALE, 0, 1)  # LEDs off: stays near black
    else:
        signal = np.clip(raw - dark, 0, None)
        level = np.clip(signal / max(np.percentile(signal, 99.5), 1.0), 0, 1) ** 0.8
    image = (level[..., None] * np.array(PREVIEW_RGB[name])).astype(np.uint8)
    out = io.BytesIO()
    Image.fromarray(image).resize((PREVIEW_SIZE, PREVIEW_SIZE), Image.LANCZOS).save(out, "PNG")
    return out.getvalue()


def write_previews(phantom_dir: Path) -> None:
    dark = decode_png16((phantom_dir / "dark.png").read_bytes())
    for name in PREVIEW_RGB:
        raw = decode_png16((phantom_dir / f"{name}.png").read_bytes())
        (phantom_dir / f"preview_{name}.png").write_bytes(preview_png(name, raw, dark))


def export_to_mobile(mobile: Path, out: Path = OUT) -> None:
    target = mobile / "assets" / "phantoms"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(out / "phantoms", target)
    for phantom_dir in target.iterdir():
        if phantom_dir.is_dir():
            write_previews(phantom_dir)
    index = json.loads((out / "index.json").read_text())
    lines = [
        "// Generated by backend/simulator/generate.py. Do not edit by hand.",
        "// Synthetic phantom frame sets from the virtual optical module (no ground truth).",
        "",
        "export type PhantomAssets = {",
        "  id: string;",
        "  description: string;",
        "  frames: Record<'blue' | 'green' | 'red' | 'nir' | 'dark', number>;",
        "  previews: Record<'blue' | 'green' | 'red' | 'nir' | 'dark', number>;",
        "};",
        "",
        "export const PHANTOMS: PhantomAssets[] = [",
    ]
    for item in index:
        pid = item["phantom_id"]
        frames = ", ".join(
            f"{b}: require('../../assets/phantoms/{pid}/{b}.png')" for b in (*BANDS, "dark")
        )
        previews = ", ".join(
            f"{b}: require('../../assets/phantoms/{pid}/preview_{b}.png')" for b in (*BANDS, "dark")
        )
        lines.append(
            f"  {{ id: {json.dumps(pid)}, description: {json.dumps(item['description'])}, "
            f"frames: {{ {frames} }}, previews: {{ {previews} }} }},"
        )
    lines += ["];", ""]
    (mobile / "src" / "device" / "phantoms.generated.ts").write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mobile", type=Path, help="path to the Expo app to bundle frames into")
    args = parser.parse_args()
    index = generate()
    if args.mobile:
        (args.mobile / "src" / "device").mkdir(parents=True, exist_ok=True)
        export_to_mobile(args.mobile)
    print(f"generated {len(index)} phantoms into {OUT}")


if __name__ == "__main__":
    main()
